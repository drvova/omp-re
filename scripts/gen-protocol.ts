#!/usr/bin/env bun
/**
 * Writes what follows from stdio/protocol.json, the one description of the
 * wire between omp and the engine:
 *
 *   extensions/re/protocol.ts   the types and tables omp's side is checked against
 *   docs/engine-protocol.md     the tables between its `<!-- protocol:… -->` marks
 *
 * The Lisp side reads the JSON itself when it loads (stdio/protocol.lisp).
 *
 *   bun scripts/gen-protocol.ts            # write both
 *   bun scripts/gen-protocol.ts --check    # exit 1 if either is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Members, type Method, readProtocol, type Type } from "./protocol.ts";

const ROOT = join(import.meta.dir, "..");
const protocol = readProtocol();

const optional = (name: string) => name.endsWith("?");
const bare = (name: string) => (optional(name) ? name.slice(0, -1) : name);
const typeName = (name: string) => name[0]!.toUpperCase() + name.slice(1);

// --- TypeScript ----------------------------------------------------------------------------------

function tsMembers(members: Members): string {
	const parts = Object.entries(members).map(([name, type]) => `${bare(name)}${optional(name) ? "?" : ""}: ${ts(type)}`);
	return parts.length === 0 ? "{}" : `{ ${parts.join("; ")} }`;
}

function ts(type: Type): string {
	if (typeof type === "string") {
		if (type.startsWith("@")) return typeName(type.slice(1));
		return { string: "string", integer: "number", number: "number", boolean: "boolean", null: "null", object: "JsonObject", json: "Json" }[type] ?? fail(`no type ${type}`);
	}
	if ("enum" in type) return type.enum.map((one) => JSON.stringify(one)).join(" | ");
	if ("array" in type) {
		const item = ts(type.array);
		return item.includes(" | ") ? `(${item})[]` : `${item}[]`;
	}
	if ("tuple" in type) return `[${type.tuple.map(ts).join(", ")}]`;
	if ("map" in type) return `{ [name: string]: ${ts(type.map)} }`;
	if ("oneOf" in type) return type.oneOf.map(ts).join(" | ");
	return tsMembers(type.members);
}

function fail(message: string): never {
	throw new Error(`gen-protocol: ${message}`);
}

function tsMethods(name: string, methods: Record<string, Method>): string {
	const rows = Object.entries(methods).map(([method, described]) => {
		const result = described.result === undefined ? "" : `; result: ${ts(described.result)}`;
		return `\t${method}: { params: ${tsMembers(described.params)}${result} };`;
	});
	return `export interface ${name} {\n${rows.join("\n")}\n}`;
}

function tsKinds(name: string, methods: Record<string, Method>): string {
	return `export const ${name} = {\n${Object.entries(methods)
		.map(([method, described]) => `\t${method}: "${described.kind}",`)
		.join("\n")}\n} as const;`;
}

function typescript(): string {
	return `${[
		"// Generated by scripts/gen-protocol.ts from stdio/protocol.json: the wire between omp and the engine.",
		"// Do not edit. Change the JSON and run `bun run gen:protocol`; `bun test` fails while this file is stale.",
		"",
		"export type Json = null | boolean | number | string | Json[] | { [key: string]: Json | undefined };",
		"export type JsonObject = { [key: string]: Json | undefined };",
		"",
		"/** The version of the wire. An engine that speaks another is refused, and refuses. */",
		`export const PROTOCOL = ${protocol.version};`,
		"",
		`export const CONSTANTS = ${JSON.stringify(protocol.constants, null, "\t")} as const;`,
		"",
		"/** The keys omp-re binds: the ones that open a view, and the ones a code view reads. The engine's help names them from the same list. */",
		`export const KEYS = ${JSON.stringify(protocol.keys, null, "\t")} as const;`,
		"",
		...Object.entries(protocol.types).map(([name, type]) => `export type ${typeName(name)} = ${ts(type)};\n`),
		"/** What omp asks the engine: each method's params, and the result of one that is a request. */",
		tsMethods("ToEngine", protocol.toEngine),
		"",
		"/** What the engine asks omp. */",
		tsMethods("ToHost", protocol.toHost),
		"",
		tsKinds("TO_ENGINE", protocol.toEngine),
		"",
		tsKinds("TO_HOST", protocol.toHost),
	].join("\n")}\n`;
}

// --- the document's tables -----------------------------------------------------------------------

const code = (text: string) => `\`${text.replaceAll("|", "\\|")}\``;

function mdType(type: Type): string {
	if (typeof type === "string") return type.startsWith("@") ? type.slice(1) : type;
	if ("enum" in type) return type.enum.map((one) => JSON.stringify(one)).join(" | ");
	if ("array" in type) {
		const item = mdType(type.array);
		return item.includes(" | ") ? `[(${item})…]` : `[${item}…]`;
	}
	if ("tuple" in type) return `[${type.tuple.map(mdType).join(", ")}]`;
	if ("map" in type) return `{name: ${mdType(type.map)}, …}`;
	if ("oneOf" in type) return type.oneOf.map(mdType).join(" | ");
	return `{${Object.entries(type.members)
		.map(([name, member]) => `${name}: ${mdType(member)}`)
		.join(", ")}}`;
}

function mdMethods(methods: Record<string, Method>): string {
	const rows = Object.entries(methods).map(([method, described]) => {
		const kind = described.kind === "notification" ? " (notification)" : "";
		const params = Object.entries(described.params)
			.map(([name, type]) => code(`${name}: ${mdType(type)}`))
			.join(", ");
		const result = described.result === undefined ? "" : code(mdType(described.result));
		return `| \`${method}\`${kind} | ${params} | ${result} |`;
	});
	return ["| Method | Params | Result |", "|---|---|---|", ...rows].join("\n");
}

const tables: Record<string, () => string> = {
	ready: () =>
		[
			"| Line | Meaning |",
			"|---|---|",
			`| \`{"ready": ${protocol.version}}\` | loaded; the number is the protocol version |`,
			'| `{"fatal": "…"}` | it could not load; the text says what to install. The process exits with status 3 |',
		].join("\n"),
	toEngine: () => mdMethods(protocol.toEngine),
	toHost: () => mdMethods(protocol.toHost),
	types: () => ["| Type | Is |", "|---|---|", ...Object.entries(protocol.types).map(([name, type]) => `| \`${name}\` | ${code(mdType(type))} |`)].join("\n"),
	constants: () => ["| Constant | Value |", "|---|---|", ...Object.entries(protocol.constants).map(([name, value]) => `| \`${name}\` | \`${JSON.stringify(value)}\` |`)].join("\n"),
	keys: () =>
		[
			"| Key | Does |",
			"|---|---|",
			...protocol.keys.views.map((key) => `| \`${key.key}\` | opens the \`${key.view}\` view |`),
			...protocol.keys.code.map((key) => `| \`${key.key}\` in a code view | ${key.long} |`),
		].join("\n"),
};

function document(current: string): string {
	let next = current;
	for (const [name, table] of Object.entries(tables)) {
		const open = `<!-- protocol:${name} -->`;
		const close = `<!-- /protocol:${name} -->`;
		const start = next.indexOf(open);
		const end = next.indexOf(close);
		if (start === -1 || end === -1 || end < start) fail(`docs/engine-protocol.md has no ${open} … ${close}`);
		next = `${next.slice(0, start + open.length)}\n${table()}\n${next.slice(end)}`;
	}
	return next;
}

// --- write, or check -----------------------------------------------------------------------------

const check = process.argv.includes("--check");
const stale: string[] = [];
const files: [string, (current: string) => string][] = [
	["extensions/re/protocol.ts", typescript],
	["docs/engine-protocol.md", document],
];
for (const [name, make] of files) {
	const path = join(ROOT, name);
	let current = "";
	try {
		current = readFileSync(path, "utf8");
	} catch {
		// Not written yet.
	}
	const next = make(current);
	if (next === current) continue;
	if (check) stale.push(name);
	else writeFileSync(path, next);
}
if (check && stale.length > 0) {
	console.error(`stale against stdio/protocol.json: ${stale.join(", ")} — run \`bun run gen:protocol\``);
	process.exit(1);
}
if (!check) console.log("protocol files written");
